// Browser smoke test for top-level workspace identity, entry flow and contextual tools.
import assert from "node:assert/strict";
import {chromium} from "playwright";
const base=process.env.STUDIO_URL||"http://127.0.0.1:8775/app/";
const browser=await chromium.launch({headless:true, ...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
try{
 await page.goto(base,{waitUntil:"domcontentloaded"});
 await page.locator("#homeWorldTitle").waitFor({state:"visible",timeout:15000});
 assert.match(await page.locator("#spaceHeading").innerText(),/World Overview/);
 assert.equal(await page.locator("body").getAttribute("data-space"),"home");
 const nav=page.locator(".space-rail button[data-panel]");
 assert.equal(await nav.count(),7);
 for(const [space,heading] of [["article","Encyclopedia"],["timeline","Chronology"],["atlas","Historical Atlas"],["network","Connections"],["media","Media Library"],["home","World Overview"]]){
  await page.locator('.space-rail button[data-panel="'+space+'"]').click();
  assert.equal(await page.locator("body").getAttribute("data-space"),space);
  assert.equal(await page.locator("#spaceHeading").innerText(),heading);
  assert.equal(await page.locator('.space-rail button[data-panel="'+space+'"]').getAttribute("aria-current"),"page");
 }
 await page.locator('.space-rail button[data-panel="boards"]').click();
 assert.equal(await page.locator("#spaceHeading").innerText(),"Moodboards");
 await page.locator("#boardEmptyCreate").click();
 await page.locator("#boardEditor").waitFor({state:"visible"});
 await page.locator("#boardAddNote").click();
 await page.locator("#boardCanvas .mood-card").first().waitFor({state:"visible"});
 assert.equal(await page.locator("#boardCanvas .mood-card").count(),1);
 await page.locator('.space-rail button[data-panel="home"]').click();
 await page.locator("#homeNew").click();
 await page.locator("#createDialog").waitFor({state:"visible"});
 await page.locator("#createTitle").fill("Navigation Test Settlement");
 await page.locator("#createType").selectOption("place");
 await page.locator("#createForm button[type=submit]").click();
 await page.locator("#writePanel").waitFor({state:"visible"});
 assert.equal(await page.locator("#breadcrumb").innerText(),"Locations / Navigation Test Settlement");
 assert.match(await page.locator("#eBody").inputValue(),/Geography and setting/);
 await page.locator("#eSummary").fill("A deliberately created sample record.");
 await page.locator("#eBody").fill("## Survey notes\nInitial data entry.");
 await page.locator('#editForm button[type=submit]').click();
 await page.locator("#notice").waitFor({state:"visible"});
 await page.locator('[data-mode=read]').click();
 await page.locator("#readPanel").waitFor({state:"visible"});
 assert.match(await page.locator("#readPanel").innerText(),/Initial data entry/);
 await page.locator('[data-mode=design]').click();
 await page.locator("#designPanel").waitFor({state:"visible"});
 await page.locator("#dTheme").selectOption("civic");
 await page.locator("#dOverrideAccent").check();
 await page.locator("#dAccent").fill("#d6b777");
 await page.locator("#layoutBlocks .design-block[data-block=gallery] button").first().click();
 assert.equal(await page.locator("#layoutBlocks .design-block").first().getAttribute("data-block"),"body");
 assert.match(await page.locator("#designPreview").innerText(),/Navigation Test Settlement/);
 await page.locator("#saveDesign").click();
 await page.locator("#designPanel").waitFor({state:"visible"});
 assert.equal(await page.locator("#dTheme").inputValue(),"civic");
 assert.equal(await page.locator("#dOverrideAccent").isChecked(),true);
 await page.locator('[data-mode=write]').click();
 assert.equal(await page.locator(".inspector").isVisible(),false);
 await page.locator('[data-mode=read]').click();
 assert.equal(await page.locator(".inspector").isVisible(),true);
 await page.locator('[data-mode=explore]').click();
 await page.locator("#explorePanel").waitFor({state:"visible"});
 await page.locator('.space-rail button[data-panel=home]').click();
 assert.equal(await page.locator("#homeMetrics .metric-card").count(),4);
 await page.locator('.space-rail button[data-panel=media]').click();
 await page.locator("#globalMediaGrid").waitFor({state:"visible"});
 await page.locator('.space-rail button[data-panel=article]').click();
 await page.locator("#entryList .entry-item").filter({hasText:"Navigation Test Settlement"}).click();
 await page.locator("#publishToggle").waitFor({state:"visible"});
 assert.match(await page.locator("#publishStatus").innerText(),/not published/);
 page.once("dialog",dialog=>dialog.accept());
 await page.locator("#publishToggle").click();
 await page.locator("#viewPublished").waitFor({state:"visible"});
 assert.match(await page.locator("#publishStatus").innerText(),/Published/);
 const readerUrl=await page.locator("#viewPublished").getAttribute("href");
 const reader=await browser.newPage({viewport:{width:1400,height:920}});
 reader.on("pageerror",error=>errors.push("reader: "+error.message));
 await reader.goto(new URL(readerUrl,base).href,{waitUntil:"domcontentloaded"});
 await reader.locator("#articleContent h1").waitFor({state:"visible"});
 assert.equal(await reader.locator("#articleContent h1").innerText(),"Navigation Test Settlement");
 assert.match(await reader.locator("#articleContent .reader-prose").innerText(),/Initial data entry/);
 assert.equal(await reader.locator("#editForm").count(),0);
 await reader.locator('a[href="#/browse"]').first().click();
 await reader.locator("#browseCards .article-card").first().waitFor({state:"visible"});
 await reader.locator("#siteSearch").count();
 await reader.locator("#searchToggle").click();
 await reader.locator("#siteSearch").fill("Navigation Test");
 await reader.locator("#quickResults .quick-result").first().waitFor({state:"visible"});
 await reader.locator("#quickResults .quick-result").first().click();
 await reader.locator("#articleContent h1").waitFor({state:"visible"});
 await reader.locator("#textSettings").click();
 await reader.locator("#fontLarger").click();
 assert.equal(await reader.locator("html").evaluate(el=>getComputedStyle(el).getPropertyValue("--read-size").trim()),"18px");
 await reader.setViewportSize({width:390,height:800});
 await reader.locator(".primary-nav").waitFor({state:"visible"});
 await reader.close();
 assert.equal(errors.length,0,errors.join("\n"));
 console.log("PASS: workspace identities, navigation, create/write/read/design/explore, overview and media");
}finally{
 await browser.close();
}
